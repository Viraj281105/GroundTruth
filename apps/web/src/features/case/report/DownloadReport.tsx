'use client';

import React, { useState } from 'react';
import { Button } from '../../../components/ds';
import { fetchReportFile, saveBlob, type ReportFormat } from './downloads';
import styles from './report.module.css';

export const downloadCopy = {
  title: 'Download institutional report',
  pdf: 'Download PDF',
  csv: 'Download CSV',
  working: 'Preparing...',
  note: 'Exports are regenerated by the API from the deterministic synthetic benchmark analysis. They are labelled simulated and are not satellite observations or a carbon calculation.',
} as const;

type Status = { kind: 'idle' } | { kind: 'busy'; format: ReportFormat } | { kind: 'done'; text: string } | { kind: 'error'; text: string };

function size(bytes: number): string {
  return bytes < 1024 ? `${bytes} B` : `${(bytes / 1024).toFixed(1)} KB`;
}

export function DownloadReport({ caseId }: { caseId: string }) {
  const [status, setStatus] = useState<Status>({ kind: 'idle' });

  async function run(format: ReportFormat) {
    if (status.kind === 'busy') return;
    setStatus({ kind: 'busy', format });
    const result = await fetchReportFile(caseId, format);
    if (!result.ok) {
      setStatus({ kind: 'error', text: result.message });
      return;
    }
    saveBlob(result.blob, result.filename);
    setStatus({
      kind: 'done',
      text: `Saved ${result.filename} (${size(result.bytes)}${result.dataMode ? `, data mode: ${result.dataMode}` : ''}).`,
    });
  }

  const busy = status.kind === 'busy' ? status.format : null;
  return (
    <div className={styles.downloads} data-print="hide">
      <h2 className={styles.h2}>{downloadCopy.title}</h2>
      <div className={styles.actions}>
        <Button variant="primary" onClick={() => run('pdf')} loading={busy === 'pdf'} disabled={busy !== null}>
          {busy === 'pdf' ? downloadCopy.working : downloadCopy.pdf}
        </Button>
        <Button variant="secondary" onClick={() => run('csv')} loading={busy === 'csv'} disabled={busy !== null}>
          {busy === 'csv' ? downloadCopy.working : downloadCopy.csv}
        </Button>
      </div>
      <p className={styles.muted}>{downloadCopy.note}</p>
      {status.kind === 'error' && (
        <p role="alert" className={styles.downloadError}>
          {status.text}
        </p>
      )}
      {status.kind === 'done' && (
        <p role="status" className={styles.muted}>
          {status.text}
        </p>
      )}
    </div>
  );
}

