"""Generate the frontend's simulated fixtures by running the real engine.

The UI's demo fixtures used to be hand-typed, which meant every engine change
(new evidence ids, new qualifiers, new refusal shapes) silently drifted away
from what the UI was built against, and every number in them was invented.
This script replaces that: each fixture is the output of ``run_analysis`` on
the synthetic fixture provider, serialised in the shape the API serves.

Everything written here is SIMULATED DATA (R6, R7). It says nothing about any
real project, and every file carries that marker.

Two things the UI draws are not in ``AnalysisResult`` today: the counterfactual
path and the per-candidate donor table. Rather than re-deriving them, the
script records the engine's own intermediate values by wrapping the functions
``run_analysis`` calls (``fit_synthetic_control``, ``match_donors``,
``in_space_placebo``). Those sections are marked ``not_served_by_api`` so the
UI cannot mistake them for API fields.

Usage, from the repository root::

    .venv/Scripts/python apps/web/scripts/generate_fixtures.py

Re-run after any engine change and commit the regenerated JSON.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

from groundtruth.contracts.ports import DataAccess, ObservationSpec
from groundtruth.contracts.request import AnalysisRequest
from groundtruth.contracts.result import AnalysisResult, EngineStatus
from groundtruth.contracts.types import TimeSeries
from groundtruth.engine import run as engine_run
from groundtruth.engine.run import run_analysis
from groundtruth.platform.cases.registry import get_case
from groundtruth.platform.config import get_settings
from groundtruth.platform.datasets.access import synthetic_access
from groundtruth.platform.reports.narrative import generate_report

OUT_DIR = Path(__file__).resolve().parent.parent / "src" / "lib" / "fixtures" / "generated"
CASE_ID = "kariba-redd"
TRUE_EFFECT = 0.06  # the API and CLI default for a synthetic run
MIN_DONORS = 10
PINNED_TIMESTAMP = "2026-01-01T00:00:00Z"

SIMULATED_MARKER = (
    "SIMULATED DATA. Generated by apps/web/scripts/generate_fixtures.py from the synthetic "
    "fixture provider. Says nothing about any real project."
)

# Clear-scene counts the synthetic provider does not report. Attaching them is
# what lets the engine's pre-treatment coverage rule run at all; without them
# it is skipped with a notice. Every unit gets a comfortable count except the
# ones listed, which are short of scenes in one pre-period.
CLEAR_SCENES_DEFAULT = 12
COVERAGE_SHORTFALL = {"donor-003": 2, "donor-017": 1, "donor-041": 3}
SHORTFALL_PERIOD = 2006

# Periods removed from a few series to drive the alignment refusal.
ALIGNMENT_GAPS = {"donor-000": (2004, 2005), "donor-001": (2016,), "donor-002": (2019,)}


class _Recorder:
    """Records the first return value of selected engine calls."""

    def __init__(self) -> None:
        self.calls: dict[str, Any] = {}

    def wrap(self, name: str, fn: Callable[..., Any]) -> Callable[..., Any]:
        def wrapped(*args: Any, **kwargs: Any) -> Any:
            out = fn(*args, **kwargs)
            self.calls.setdefault(name, out)
            return out

        return wrapped


@contextmanager
def _recording() -> Iterator[_Recorder]:
    recorder = _Recorder()
    names = ("fit_synthetic_control", "match_donors", "in_space_placebo", "align_panel")
    originals = {n: getattr(engine_run, n) for n in names}
    try:
        for n, fn in originals.items():
            setattr(engine_run, n, recorder.wrap(n, fn))
        yield recorder
    finally:
        for n, fn in originals.items():
            setattr(engine_run, n, fn)


class _EditedObservations:
    """Delegating observation port that edits series before the engine sees them."""

    def __init__(self, inner: Any, edit: Callable[[TimeSeries], TimeSeries]) -> None:
        self._inner = inner
        self._edit = edit

    def series(self, spec: ObservationSpec) -> TimeSeries:
        return self._edit(self._inner.series(spec))

    def dataset(self, indicator: Any) -> Any:
        return self._inner.dataset(indicator)

    def provenance(self, spec: ObservationSpec) -> Any:
        return self._inner.provenance(spec)


def _with_clear_scenes(series: TimeSeries) -> TimeSeries:
    shortfall = COVERAGE_SHORTFALL.get(series.unit_id)
    counts = tuple(
        shortfall if (shortfall is not None and p == SHORTFALL_PERIOD) else CLEAR_SCENES_DEFAULT
        for p in series.periods
    )
    return series.model_copy(update={"n_valid_observations": counts})


def _with_gaps(series: TimeSeries) -> TimeSeries:
    gaps = ALIGNMENT_GAPS.get(series.unit_id)
    if not gaps:
        return series
    keep = [i for i, p in enumerate(series.periods) if p not in gaps]
    return series.model_copy(
        update={
            "periods": tuple(series.periods[i] for i in keep),
            "values": tuple(series.values[i] for i in keep),
        }
    )


def _request(*, full_robustness: bool) -> AnalysisRequest:
    case = get_case(CASE_ID)
    request = case.to_request(
        data_mode="simulated", seed=get_settings().random_seed, min_donors=MIN_DONORS
    )
    if not full_robustness:
        return request
    # The API does not yet expose these flags; the fixture turns them on so the
    # UI can be built against every evidence family the engine can emit.
    robustness = request.robustness.model_copy(
        update={"in_time_placebo": True, "specification_curve": True}
    )
    return request.model_copy(update={"robustness": robustness})


def _access(request: AnalysisRequest, edit: Callable[[TimeSeries], TimeSeries]) -> DataAccess:
    base = synthetic_access(request, true_effect=TRUE_EFFECT)
    return base.model_copy(update={"observations": _EditedObservations(base.observations, edit)})


def _generated_meta(result: AnalysisResult, scenario: str, description: str) -> dict[str, Any]:
    return {
        "marker": SIMULATED_MARKER,
        "scenario": scenario,
        "description": description,
        "case_id": result.case_id,
        "engine_version": result.engine.engine_version,
        "contract_version": result.contract_version,
        "spec_hash": result.spec_hash,
        "seed": result.seed,
        "true_effect_injected": TRUE_EFFECT,
    }


def _verification_response(result: AnalysisResult) -> dict[str, Any]:
    """The body ``POST /cases/{id}/verify`` returns for a completed run."""
    bundle = result.bundle
    assert bundle is not None and bundle.verdict is not None
    report = generate_report(bundle)
    return {
        "run_id": result.run_id,
        "case_id": result.case_id,
        "spec_hash": result.spec_hash,
        "engine_version": result.engine.engine_version,
        "contract_version": result.contract_version,
        "data_mode": "simulated" if result.is_simulated else "observed",
        # Wall-clock time is not reproducible, so it is pinned rather than recorded.
        "duration_ms": 0.0,
        "verdict_label": bundle.verdict.label.value,
        "verdict_rationale": bundle.verdict.rationale,
        "caveats": list(bundle.verdict.caveats),
        "warnings": list(bundle.warnings),
        "bundle": json.loads(bundle.model_dump_json()),
        "report_markdown": report.markdown,
        "report_generator": report.generator,
    }


def _completed() -> dict[str, Any]:
    request = _request(full_robustness=True)
    with _recording() as rec:
        result = run_analysis(request, _access(request, _with_clear_scenes))
    if result.status is not EngineStatus.COMPLETED:
        raise SystemExit(f"expected a completed run, got {result.status}: {result.error}")

    panel = rec.calls["align_panel"]
    fit = rec.calls["fit_synthetic_control"]
    pool = rec.calls["match_donors"]
    placebo = rec.calls["in_space_placebo"]

    observed = [*fit.treated_pre.tolist(), *fit.treated_post.tolist()]
    synthetic = [*fit.synthetic_pre.tolist(), *fit.synthetic_post.tolist()]
    return {
        "_generated": _generated_meta(
            result,
            "completed",
            "Completed run with in-time placebo and specification curve enabled, and "
            "clear-scene counts attached so the pre-treatment coverage rule is applied.",
        ),
        "verification": _verification_response(result),
        "not_served_by_api": {
            "note": (
                "Intermediate engine values recorded during this run. AnalysisResult does not "
                "carry them, so the API cannot serve them yet."
            ),
            "counterfactual_path": {
                "periods": list(panel.periods),
                "treatment_boundary_period": panel.post_periods[0],
                "observed": observed,
                "synthetic": synthetic,
            },
            "donor_pool": [
                {
                    "unit_id": m.unit_id,
                    "admitted": m.admitted,
                    "distance": m.distance,
                    "exclusion_reason": m.exclusion_reason,
                }
                for m in pool.matches
            ],
            "placebo_distribution": {
                "statistic": placebo.statistic_name,
                "observed_statistic": placebo.observed_statistic,
                "placebo_statistics": list(placebo.placebo_statistics),
            },
        },
    }


def _refused_alignment() -> dict[str, Any]:
    request = _request(full_robustness=False)
    result = run_analysis(request, _access(request, _with_gaps))
    if result.status is EngineStatus.COMPLETED or result.error is None:
        raise SystemExit("expected the alignment scenario to be refused")
    if result.error.stage != "alignment":
        raise SystemExit(f"expected a refusal at alignment, got {result.error.stage}")
    error = result.error
    return {
        "_generated": _generated_meta(
            result,
            "refused-alignment",
            "Several donor series are missing window periods, so the engine refuses at the "
            "alignment stage rather than fitting a misaligned panel.",
        ),
        # The HTTP error body the API returns for a refusal (platform/api/app.py).
        "http_status": 422,
        "error_body": {
            "detail": {
                "code": error.code.value,
                "message": error.message,
                "stage": error.stage,
                "is_refusal": error.is_refusal,
                "remediation": error.remediation,
                "run_id": result.run_id,
            }
        },
        "not_served_by_api": {
            "note": (
                "AnalysisError.detail as the engine produced it. The API's refusal body does "
                "not include it yet, so per-unit missing periods are fixture-only."
            ),
            "error_detail": error.detail,
        },
    }


def _pin_volatile(node: Any, scenario: str) -> Any:
    """Replace wall-clock and random fields so regeneration gives a clean diff.

    Only ``run_id`` and ``retrieved_at`` are touched. Neither feeds any number:
    the numeric output is already fixed by spec_hash + seed + engine version (R8).
    """
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for key, value in node.items():
            if key == "run_id" and isinstance(value, str):
                out[key] = f"run_fixture_{scenario}"
            elif key == "retrieved_at" and isinstance(value, str):
                out[key] = PINNED_TIMESTAMP
            else:
                out[key] = _pin_volatile(value, scenario)
        return out
    if isinstance(node, list):
        return [_pin_volatile(v, scenario) for v in node]
    return node


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, payload in (
        (f"{CASE_ID}.completed.json", _completed()),
        (f"{CASE_ID}.refused-alignment.json", _refused_alignment()),
    ):
        scenario = payload["_generated"]["scenario"]
        payload["_generated"]["pinned_fields"] = {
            "run_id": "per scenario",
            "retrieved_at": PINNED_TIMESTAMP,
        }
        payload = _pin_volatile(payload, scenario)
        path = OUT_DIR / name
        path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
