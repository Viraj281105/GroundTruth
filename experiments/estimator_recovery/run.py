"""Estimator recovery experiment.

Question: on panels generated by the process synthetic control assumes, does the
estimator recover a known injected effect, and does the placebo suite
distinguish a real effect from a null?

This is the one experiment in this directory that has actually been run — the
same checks are asserted in ``tests/test_causal.py``. This script sweeps a wider
grid so the *boundaries* of reliability are visible: how short a pre-period, how
small a donor pool and how much noise the method tolerates before it stops
working.

Run:
    python experiments/estimator_recovery/run.py --out results/recovery.json
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from groundtruth import __version__
from groundtruth.contracts.errors import EstimationError, InsufficientDataError
from groundtruth.engine.causal.synthetic_control import fit_synthetic_control
from groundtruth.engine.uncertainty.placebo import in_space_placebo


@dataclass
class Condition:
    """One cell of the sweep."""

    n_donors: int
    n_pre: int
    n_post: int
    noise_sd: float
    true_effect: float
    n_replicates: int


@dataclass
class Outcome:
    """Aggregate performance for one condition."""

    condition: dict[str, float]
    mean_estimate: float
    bias: float
    rmse: float
    coverage_of_sign: float
    mean_placebo_p: float
    detection_rate: float
    n_failures: int


def make_panel(condition: Condition, rng: np.random.Generator, *, with_effect: bool) -> np.ndarray:
    """Generate a latent-factor panel; column 0 is the treated unit."""
    n_periods = condition.n_pre + condition.n_post
    n_units = condition.n_donors + 1
    n_factors = 3

    factors = rng.normal(size=(n_factors, n_periods)).cumsum(axis=1) * 0.04 + 0.6
    loadings = rng.dirichlet(np.ones(n_factors), size=n_units)
    panel = (loadings @ factors).T + rng.normal(0.0, condition.noise_sd, size=(n_periods, n_units))
    if with_effect:
        panel[condition.n_pre :, 0] += condition.true_effect
    return panel


def evaluate(condition: Condition, seed: int) -> Outcome:
    """Run all replicates for one condition."""
    rng = np.random.default_rng(seed)
    unit_ids = tuple(f"u{i:03d}" for i in range(condition.n_donors + 1))

    estimates: list[float] = []
    placebo_p: list[float] = []
    failures = 0

    for _ in range(condition.n_replicates):
        panel = make_panel(condition, rng, with_effect=True)
        try:
            fit = fit_synthetic_control(
                panel[:, 0],
                panel[:, 1:],
                unit_ids[1:],
                condition.n_pre,
                min_pre_periods=3,
            )
            estimates.append(fit.average_effect)
            result = in_space_placebo(panel, unit_ids, 0, condition.n_pre, min_pre_periods=3)
            placebo_p.append(result.p_value)
        except (EstimationError, InsufficientDataError):
            failures += 1

    if not estimates:
        return Outcome(
            condition=asdict(condition),
            mean_estimate=float("nan"),
            bias=float("nan"),
            rmse=float("nan"),
            coverage_of_sign=float("nan"),
            mean_placebo_p=float("nan"),
            detection_rate=float("nan"),
            n_failures=failures,
        )

    arr = np.asarray(estimates)
    truth = condition.true_effect
    return Outcome(
        condition=asdict(condition),
        mean_estimate=float(arr.mean()),
        bias=float(arr.mean() - truth),
        rmse=float(np.sqrt(np.mean((arr - truth) ** 2))),
        coverage_of_sign=float(np.mean(np.sign(arr) == np.sign(truth))),
        mean_placebo_p=float(np.mean(placebo_p)) if placebo_p else float("nan"),
        detection_rate=float(np.mean(np.asarray(placebo_p) < 0.10)) if placebo_p else 0.0,
        n_failures=failures,
    )


def default_grid(n_replicates: int) -> list[Condition]:
    """The sweep: vary one factor at a time around a realistic centre."""
    base = {"n_donors": 30, "n_pre": 10, "n_post": 8, "noise_sd": 0.01, "true_effect": 0.05}
    grid: list[Condition] = []
    for n_pre in (5, 8, 10, 15):
        grid.append(Condition(**{**base, "n_pre": n_pre}, n_replicates=n_replicates))
    for n_donors in (10, 20, 30, 50):
        grid.append(Condition(**{**base, "n_donors": n_donors}, n_replicates=n_replicates))
    for noise_sd in (0.005, 0.01, 0.02, 0.04):
        grid.append(Condition(**{**base, "noise_sd": noise_sd}, n_replicates=n_replicates))
    for true_effect in (0.0, 0.02, 0.05, 0.10):
        grid.append(Condition(**{**base, "true_effect": true_effect}, n_replicates=n_replicates))
    return grid


def main() -> int:
    """Run the sweep and write results."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="experiments/estimator_recovery/results/recovery.json")
    parser.add_argument("--replicates", type=int, default=20)
    parser.add_argument("--seed", type=int, default=20260101)
    args = parser.parse_args()

    outcomes = [
        evaluate(condition, args.seed + i)
        for i, condition in enumerate(default_grid(args.replicates))
    ]

    payload = {
        "experiment": "estimator_recovery",
        "generated_at": datetime.now(UTC).isoformat(),
        "groundtruth_version": __version__,
        "seed": args.seed,
        "data": "SIMULATED - latent factor panels, not real observations",
        "outcomes": [asdict(o) for o in outcomes],
    }

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    header = (
        f"{'n_pre':>6} {'donors':>7} {'noise':>7} {'truth':>7} {'bias':>9} {'rmse':>8} {'det':>6}"
    )
    print(header)
    for o in outcomes:
        c = o.condition
        print(
            f"{c['n_pre']:>6} {c['n_donors']:>7} {c['noise_sd']:>7.3f} "
            f"{c['true_effect']:>7.3f} {o.bias:>9.4f} {o.rmse:>8.4f} {o.detection_rate:>6.2f}"
        )
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
